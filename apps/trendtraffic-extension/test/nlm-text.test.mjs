/**
 * Тест текстовых матчеров NotebookLM. Гоняется в node, браузер и живой NotebookLM НЕ нужны:
 *   node apps/trendtraffic-extension/test/nlm-text.test.mjs
 *
 * Зачем: подписи в студии Google обрезаются вёрсткой («Аудиопе…»), а сами названия он переписывает
 * при каждом редизайне. Раньше это ловилось только глазами на живой странице — теперь тест держит
 * оба набора формулировок (до редизайна и после) и обе формы, полную и обрезанную.
 *
 * ДОБАВЛЯЯ синоним в GEN_UI или основу в ARTKIND_RE — добавь сюда случай, иначе следующий редизайн
 * снова придётся ловить руками.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
// nlm-text.js — IIFE, кладущая себя в globalThis: исполняем как есть, без сборщика.
new Function(readFileSync(join(here, '..', 'src', 'nlm-text.js'), 'utf8'))();
const T = globalThis.TT_NLM_TEXT;
if (!T) { console.error('nlm-text.js не выставил globalThis.TT_NLM_TEXT'); process.exit(1); }

let pass = 0;
const fails = [];
const check = (group, name, actual, expected) => {
  if (actual === expected) { pass++; return; }
  fails.push(`${group} · ${name}: ждали ${expected}, получили ${actual}`);
};
const ok = (g, n, v) => check(g, n, !!v, true);
const no = (g, n, v) => check(g, n, !!v, false);

// ─────────────────────────────────────────────────────────────────────────────
// 1. Плитки студии: обрезанная подпись должна находиться по полному названию
// ─────────────────────────────────────────────────────────────────────────────
{
  const g = '1. плитки студии';
  const L = T.looseIncludes;

  // как было до редизайна — не должно сломаться
  ok(g, 'полная подпись', L('Аудиопересказ', 'аудиопересказ'));
  ok(g, 'подпись в фразе', L('Кнопка: Аудиопересказ', 'аудиопересказ'));
  ok(g, 'регистр не важен', L('АУДИОПЕРЕСКАЗ', 'аудиопересказ'));

  // как стало: вёрстка режет подпись многоточием
  ok(g, 'обрезка «Аудиопе…»', L('Аудиопе…', 'аудиопересказ'));
  ok(g, 'обрезка «Видеопе…»', L('Видеопе…', 'видеопересказ'));
  ok(g, 'обрезка «Менталь…»', L('Менталь…', 'ментальная карта'));
  ok(g, 'обрезка «Инфогра…»', L('Инфогра…', 'инфографика'));
  ok(g, 'обрезка «Презент…»', L('Презент…', 'презентация'));
  ok(g, 'обрезка «Таблица…»', L('Таблица…', 'таблица данных'));
  ok(g, 'обрезка тремя точками', L('Аудиопе...', 'аудиопересказ'));

  // кнопка настройки: огрызок стоит в СЕРЕДИНЕ искомого — ради этого случая матч по «содержит»
  ok(g, 'обрезка «Настроить аудиопе…»', L('Настроить аудиопе…', 'настроить аудиопересказ'));
  ok(g, 'обрезка «Настроить ментальн…»', L('Настроить ментальн…', 'настроить ментальную карту'));

  // ложные срабатывания
  no(g, 'чужое слово на ту же букву', L('Аудитория', 'аудиопересказ'));
  no(g, 'огрызок короче порога', L('Ауд…', 'аудиопересказ'));
  no(g, 'посторонний текст', L('Чат', 'аудиопересказ'));
  no(g, 'пустая строка', L('', 'аудиопересказ'));
  no(g, 'обрезка не от того слова', L('Создаю…', 'аудиопересказ'));
}

// ─────────────────────────────────────────────────────────────────────────────
// 2. Опознание карточки артефакта (ARTKIND_RE) — все девять типов, RU и EN
// ─────────────────────────────────────────────────────────────────────────────
{
  const g = '2. типы артефактов';
  const R = (s) => T.ARTKIND_RE.test(s);

  for (const s of ['Аудиопересказ', 'Аудиопе…', 'Видеопересказ', 'Видеопе…', 'Инфографика', 'Инфогра…',
    'Ментальная карта', 'Менталь…', 'Презентация', 'Презент…', 'Таблица данных', 'Таблица…',
    'Карточки', 'Тест', 'Отчёты', 'Отчеты']) ok(g, `RU «${s}»`, R(s));

  for (const s of ['Audio Overview', 'Video Overview', 'Mind map', 'Mindmap', 'Infographic',
    'Flashcards', 'Quiz', 'Report', 'Slide deck', 'Data table', 'Study guide']) ok(g, `EN «${s}»`, R(s));

  ok(g, 'старый формат «Подробный анализ»', R('Подробный анализ'));
  no(g, 'не артефакт: Источники', R('Источники'));
  no(g, 'не артефакт: Чат', R('Чат'));
  no(g, 'не артефакт: Добавить', R('Добавить'));
}

// ─────────────────────────────────────────────────────────────────────────────
// 3. «Идёт генерация» против «готовая работа»
// ─────────────────────────────────────────────────────────────────────────────
{
  const g = '3. детект генерации';
  const G = T.isGeneratingText;

  ok(g, 'плейсхолдер «вернитесь через»', G('Создаю аудиопересказ, вернитесь через несколько минут'));
  ok(g, 'плейсхолдер видео', G('Генерация поясняющего видео. Это может занять некоторое время.'));
  ok(g, 'новый: «вернитесь позже»', G('Готовим отчёт, вернитесь позже'));
  ok(g, 'EN generating', G('Generating audio overview'));
  ok(g, 'EN preparing', G('Preparing your report'));
  ok(g, 'EN check back', G('Check back in a few minutes'));
  ok(g, 'EN this may take', G('This may take a few minutes'));
  ok(g, 'глагол + тип', G('Создаётся инфографика'));

  // гейт по длительности: у ГОТОВОЙ работы всегда есть m:ss
  no(g, 'готовая работа с длительностью', G('Подробный анализ 19:44'));
  no(g, 'глагол в НАЗВАНИИ готовой', G('Создаю бренд 6:46'));
  no(g, 'просто название типа', G('Аудиопересказ'));
  no(g, 'посторонний текст', G('Источники и чат'));
}

// ─────────────────────────────────────────────────────────────────────────────
// 4. Пункт меню «Скачать» — но не «Скачать блокнот»
// ─────────────────────────────────────────────────────────────────────────────
{
  const g = '4. пункт «Скачать»';
  const D = T.isDownloadItem;

  ok(g, 'лигатура + подпись', D('save_alt Скачать'));
  ok(g, 'только подпись', D('Скачать'));
  ok(g, 'EN', D('Download'));
  ok(g, 'EN с лигатурой', D('save_alt Download'));
  ok(g, '«Сохранить»', D('Сохранить'));

  no(g, 'скачать БЛОКНОТ — не тот пункт', D('Скачать блокнот'));
  no(g, 'download notebook', D('Download notebook'));
  no(g, 'посторонний пункт', D('Переименовать'));
}

// ─────────────────────────────────────────────────────────────────────────────
// 5. Форма входа Google под новым брендом
// ─────────────────────────────────────────────────────────────────────────────
{
  const g = '5. форма входа';
  // findByText сравнивает вхождением, поэтому проверяем ровно это
  const hit = (label) => T.SIGNIN_WORDS.some((w) => T.norm(label).includes(T.norm(w)));

  ok(g, 'старая подпись NotebookLM', hit('Sign in to NotebookLM'));
  ok(g, 'новая подпись Notebook', hit('Sign in to Notebook'));
  ok(g, 'бренд Gemini', hit('Sign in to Gemini Notebook'));
  ok(g, 'кнопка Google', hit('Sign in with Google'));
  ok(g, 'RU', hit('Войдите в аккаунт Google'));

  no(g, 'не форма входа: настройки', hit('Настройки аккаунта'));
  no(g, 'не форма входа: выход', hit('Выйти из аккаунта'));
}

// ─────────────────────────────────────────────────────────────────────────────
// 6. Чип «9:16»: где предлагаем и, главное, где НЕ трогаем
// ─────────────────────────────────────────────────────────────────────────────
{
  const g = '6. чип 9:16';
  const rule = (head) => T.V916.find((v) => v.re.test(head));

  ok(g, 'видеообзор', !!rule('Настройка видеообзора'));
  ok(g, 'видео обрезано', !!rule('Настроить видеопе…'));
  ok(g, 'инфографика обрезана', !!rule('Настроить инфогра…'));
  ok(g, 'презентация обрезана', !!rule('Настроить презент…'));
  ok(g, 'отчёт', !!rule('Настройка отчёта'));
  ok(g, 'EN video', !!rule('Customize video overview'));

  // аудио вертикального формата не имеет — чип предлагать нельзя
  no(g, 'аудио НЕ предлагаем', !!rule('Настроить аудиопересказ'));

  // диалог «Добавить источники» трогать нельзя: там textarea — это ПОИСК источников (баг 15.07)
  const S = (s) => T.SRC_DLG_RE.test(s);
  ok(g, 'диалог источников: перетащить', S('Перетащить файлы'));
  ok(g, 'диалог источников: поиск', S('Найдите новые источники в интернете'));
  ok(g, 'диалог источников: EN', S('Upload a file'));
  ok(g, 'диалог источников: copied text', S('Copied text'));
  no(g, 'диалог настройки студии — не источники', S('Настройка видеообзора. На чём сделать акцент?'));
}

// ─────────────────────────────────────────────────────────────────────────────
// 7. Заголовок карточки: стабильность между сканами (иначе дубликаты в Галерее)
// ─────────────────────────────────────────────────────────────────────────────
{
  const g = '7. заголовок карточки';
  const C = T.cardTitle;

  check(g, 'длительность и тип отрезаются', C('Анатомия ловушки мигрантов 7:46 · Пояснительное видео'), 'Анатомия ловушки мигрантов');
  check(g, 'наша кнопка ⬇TT не липнет', C('Анатомия ловушки ⬇TT'), 'Анатомия ловушки');
  check(g, 'состояние кнопки не липнет', C('Анатомия ловушки ⬇TT ✓'), 'Анатомия ловушки');
  check(g, 'snake_case-лигатуры вычищаются', C('Отчёт по рынку save_alt more_vert'), 'Отчёт по рынку');
  check(g, 'мусор плеера → фолбэк', C('sharedownload Посмотреть запрос'), 'Артефакт NotebookLM');
  check(g, 'пустой текст → фолбэк', C(''), 'Артефакт NotebookLM');

  // главное свойство: два скана одной карточки дают ОДИН заголовок
  check(g, 'идемпотентность', C(C('Анатомия ловушки мигрантов 7:46 · Пояснительное видео')), 'Анатомия ловушки мигрантов');
}

// ─────────────────────────────────────────────────────────────────────────────
console.log(`\nnlm-text: пройдено ${pass}, провалено ${fails.length}`);
if (fails.length) {
  console.error('\nПРОВАЛЫ:');
  for (const f of fails) console.error('  ✗ ' + f);
  process.exit(1);
}
console.log('✓ все проверки зелёные\n');
